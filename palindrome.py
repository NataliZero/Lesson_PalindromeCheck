def is_palindrome(string):
    """
    Проверяет, является ли строка палиндромом.
    :param string: входная строка
    :return: True, если строка палиндром, иначе False
    """
    # Шаг 1. Привести строку к нижнему регистру.
    # Это позволит игнорировать разницу между заглавными и строчными буквами.
    string = string.lower()

    # Шаг 2. Удалить все лишние символы, оставив только буквы и цифры.
    # Используем генератор, чтобы создать новую строку без пробелов и знаков препинания.
    cleaned_string = ''.join(char for char in string if char.isalnum())

    # Шаг 3. Сравнить очищенную строку с ее перевернутой версией.
    # Оператор [::-1] переворачивает строку.
    return cleaned_string == cleaned_string[::-1]


# Шаг 4. Тестирование функции
if __name__ == "__main__":
    # Примеры для проверки
    test_strings = [
        "А роза упала на лапу Азора",
        "12321",
        "Просто текст",
        "Madam",
        "Was it a car or a cat I saw",
    ]

    # Для каждой строки вызываем функцию и выводим результат
    for test in test_strings:
        print(f"Строка: '{test}' → Палиндром? {is_palindrome(test)}")
